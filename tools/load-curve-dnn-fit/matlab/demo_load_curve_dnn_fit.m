function demo_load_curve_dnn_fit()
%DEMO_LOAD_CURVE_DNN_FIT Fit the synthetic residential day and save the figure.
%   From this folder, call demo_load_curve_dnn_fit. The figure is written to
%   examples/output/load_curve_dnn_fit_demo_matlab.png (gitignored). Set
%   'show', true on the load_curve_dnn_fit call below to leave the window open.

    here = fileparts(mfilename('fullpath'));
    addpath(here);
    toolDir = fileparts(here);
    csvPath = fullfile(toolDir, 'examples', 'data', 'synthetic_daily_load_kw.csv');
    outDir = fullfile(toolDir, 'examples', 'output');
    if exist(outDir, 'dir') ~= 7
        mkdir(outDir);
    end
    outPng = fullfile(outDir, 'load_curve_dnn_fit_demo_matlab.png');
    outCsv = fullfile(outDir, 'load_curve_dnn_fit_demo_matlab.csv');
    result = load_curve_dnn_fit(csvPath, ...
        'degree', 5, ...
        'hidden', 8, ...
        'epochs', 2000, ...
        'learning_rate', 0.05, ...
        'seed', 0, ...
        'normalize', 'peak', ...
        'output_png', outPng, ...
        'output_csv', outCsv, ...
        'show', false);
    fprintf(['load-curve-dnn-fit: poly_rmse=%.4f poly_mae=%.4f poly_max_abs=%.4f ', ...
        'dnn_rmse=%.4f dnn_mae=%.4f dnn_max_abs=%.4f\n'], ...
        result.poly_rmse, result.poly_mae, result.poly_max_abs, ...
        result.dnn_rmse, result.dnn_mae, result.dnn_max_abs);
    fprintf('%s\n', result.summary);
    fprintf('saved %s\n', result.output_png);
    fprintf('saved %s\n', result.output_csv);
end
